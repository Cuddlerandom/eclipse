import {MercenaryAnimator,MERCENARY_CLIPS,drawMercenaryFrame} from "./mercenary-animator.js";
function assert(ok,msg){if(!ok)throw new Error(msg);}
const a=new MercenaryAnimator();
assert(a.sample().state==="idle","initial idle");
assert(a.sample().index===0,"initial frame");
a.setState("run").update(1/12);assert(a.sample().index===1,"run advances one frame");
a.update(7/12);assert(a.sample().index===0,"run wraps to zero");
a.face(-1);assert(a.sample().facing===-1,"facing left");
a.face(0);assert(a.sample().facing===-1,"zero input retains facing");
a.setState("attack").update(10);assert(a.sample().index===7&&a.sample().done,"attack clamps at last frame");
a.setState("attack",{restart:true});assert(a.sample().index===0,"restart same state");
a.update(-1);assert(a.sample().index===0,"negative dt ignored");
for(const [name,clip] of Object.entries(MERCENARY_CLIPS))assert(clip.frames>0&&clip.fps>0,"valid clip "+name);
const ops=[];const ctx={save(){ops.push("save")},translate(...x){ops.push(["translate",...x])},scale(...x){ops.push(["scale",...x])},drawImage(...x){ops.push(["drawImage",...x])},restore(){ops.push("restore")}};
assert(drawMercenaryFrame(ctx,{}, {state:"run",index:2,facing:-1},{x:100,y:200,frameWidth:96,frameHeight:112,anchorX:48,anchorY:104}),"render success");
assert(ops.some(x=>Array.isArray(x)&&x[0]==="drawImage"&&x[2]===192&&x[3]===112),"correct atlas region");
assert(ops.some(x=>Array.isArray(x)&&x[0]==="scale"&&x[1]===-1),"mirror");
assert(!drawMercenaryFrame(ctx,null,a.sample(),{x:0,y:0,frameWidth:96,frameHeight:112}),"missing atlas safe");
assert(!drawMercenaryFrame(ctx,{}, {state:"run",index:999,facing:1},{x:0,y:0,frameWidth:96,frameHeight:112}),"reject invalid atlas frame");
console.log("Mercenary animator tests passed");
